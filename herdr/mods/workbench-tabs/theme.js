/** Writes the theme on a machine (null: this one). */
export async function writeTheme(text, on) {
  const r = await exec("sh", ["-c", 'mkdir -p "$HOME/.config/helix/themes" && printf %s "$1" > "$HOME/.config/helix/themes/herdr.toml"', "theme", text], { on });
  if (r.code !== 0) throw new Error(r.stderr || "cannot write the helix theme");
}

/** Loads the herdr theme in one hx. A fresh one first gets to draw its first screen. */
export async function applyTheme(address, fresh) {
  const on = address.includes("/") ? address.split("/")[0] : null, local = address.split("/").pop();
  if (fresh) await exec("hc", ["wait", local, "--output", "sel", "--timeout", "10"], { on }).catch(() => null);
  await exec("hc", ["keys", local, "esc", "alt+f11"], { on });
}
