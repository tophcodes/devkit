// Keeps the tabs' own hx in herdr's colors. A Helix theme named "herdr" is generated from
// theme() and written to ~/.config/helix/themes/herdr.toml on each machine that runs one
// of those hx; alt-f11, bound to `:theme herdr` in the helix config, loads it. Runs again
// whenever the colors change and for every new hx.
// Ceiling: one theme file per machine. Two windows with different herdr themes on the
// same machine overwrite each other's file; the last change wins.
import { exec } from "herdr";

// herdr colors may carry alpha (#rrggbbaa); Helix takes #rrggbb, so blend over the background.
function solid(color, bg) {
  if (!/^#[0-9a-f]{8}$/i.test(color)) return color.slice(0, 7);
  const ch = (c, i) => parseInt(c.slice(i, i + 2), 16), a = ch(color, 7) / 255;
  return "#" + [1, 3, 5].map((i) => Math.round(ch(color, i) * a + ch(bg, i) * (1 - a)).toString(16).padStart(2, "0")).join("");
}

